// PyFile is the generated Python test of a case file: cases/vlan/add.yaml → cases/vlan/test_vlan_add.py
// (the folder in the name keeps file names unique for pytest without __init__ files).
func PyFile(caseFile string) string {
	caseFile = filepath.ToSlash(caseFile)
	dir, base := filepath.ToSlash(filepath.Dir(caseFile)), strings.TrimSuffix(filepath.Base(caseFile), filepath.Ext(caseFile))
	sub := strings.TrimPrefix(strings.TrimPrefix(dir, "cases"), "/")
	name := pyIdent(base)
	if sub != "" {
		name = pyIdent(strings.ReplaceAll(sub, "/", "_")) + "_" + name
	}
	return dir + "/test_" + name + ".py"
}

func pyIdent(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		case b.Len() > 0 && !strings.HasSuffix(b.String(), "_"):
			b.WriteByte('_')
		}
	}
	if n := strings.Trim(b.String(), "_"); n != "" {
		return n
	}
	return "case"
}

// pyStr quotes s for Python: a raw string for regular expressions with backslashes, else a JSON
// string (valid Python).
func pyStr(s string) string {
	if strings.Contains(s, `\`) && !strings.ContainsAny(s, "'\n\r") && !strings.HasSuffix(s, `\`) {
		return "r'" + s + "'"
	}
	b, _ := json.Marshal(s)
	return string(b)
}

func pyDict(m map[string]string) string {
	if len(m) == 0 {
		return "{}"
	}
	b, _ := json.Marshal(m) // sorted keys; valid Python
	return string(b)
}

// GeneratePython writes a case as a Python test (unittest.TestCase from lib/python/twtest.py; pytest
// runs it too); each step is a subTest.
func GeneratePython(c Case, caseFile string) ([]byte, error) {
	caseFile = filepath.ToSlash(caseFile)
	depth := strings.Count(filepath.ToSlash(filepath.Dir(caseFile)), "/") + 1
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Code generated by Termwright from %s. DO NOT EDIT - change the YAML (or record it again) and save it.\n", caseFile)
	b.WriteString("import os\nimport sys\n\n")
	fmt.Fprintf(&b, "sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), %s\"lib\", \"python\"))\n", strings.Repeat(`"..", `, depth))
	b.WriteString("import twtest  # noqa: E402\n")
	if usesCalls(c) {
		b.WriteString("import twprocs  # noqa: E402\n")
	}
	b.WriteString("\n\n")
	base := strings.TrimSuffix(filepath.Base(caseFile), filepath.Ext(caseFile))
	name := c.Name
	if name == "" {
		name = base
	}
	fmt.Fprintf(&b, "class Test%s(twtest.TestCase):\n", goIdent(base))
	doc := oneLine(name)
	if c.Description != "" {
		doc += ": " + oneLine(c.Description)
	}
	fmt.Fprintf(&b, "    %s\n\n    VARS = %s\n", pyStr(doc), pyDict(c.Vars))
	if req := RequireMap(c); len(req) > 0 {
		fmt.Fprintf(&b, "    REQUIRES = %s\n", pyDict(req))
	}
	if len(c.Params) > 0 {
		var ps []string
		for _, p := range c.Params {
			ps = append(ps, pyDict(p))
		}
		fmt.Fprintf(&b, "    PARAMS = [%s]\n", strings.Join(ps, ", "))
	}
	b.WriteString("\n    def test_steps(self):\n        for tw in self.cases():\n")
	ind := "            "
	if len(c.Restore) > 0 {
		var ks, ss []string
		for _, k := range c.Restore {
			ks = append(ks, pyStr(k))
		}
		for _, x := range Sessions(c, nil) {
			ss = append(ss, pyStr(x))
		}
		fmt.Fprintf(&b, "%stw.restore([%s], [%s])\n", ind, strings.Join(ks, ", "), strings.Join(ss, ", "))
	}
	for _, ps := range phased(c) {
		pyStep(&b, ps.st, ps.i, ps.phase, ind, "")
	}
	if len(c.Restore) > 0 {
		b.WriteString(ind + "tw.finish()\n")
	}
	if len(c.Steps) == 0 {
		b.WriteString(ind + "self.fail(\"the test has no steps\")\n")
	}
	return b.Bytes(), nil
}

func pyExpect(e Expect) string {
	switch {
	case e.Table != nil:
		t := e.Table
		w := pyDict(t.Where)
		switch {
		case t.Rows != nil:
			return fmt.Sprintf("a.row_count(%s).equals(%q)", w, strconv.Itoa(*t.Rows))
		case t.Column == "" && t.Exists != nil && !*t.Exists:
			return "a.row_count(" + w + ").equals(\"0\")"
		case t.Column == "":
			return "a.row_count(" + w + ").greater(0)"
		case t.Matches != "":
			return "a.cell(" + w + ", " + pyStr(t.Column) + ").matches(" + pyStr(t.Matches) + ")"
		}
		x := pyExpect(Expect{Field: "\x00", Equals: t.Equals, NotEquals: t.NotEquals, Greater: t.Greater, Less: t.Less, Exists: t.Exists})
		return "a.cell(" + w + ", " + pyStr(t.Column) + ")" + x[strings.Index(x, ")")+1:]
	case e.Contains != "":
		return "a.contains(" + pyStr(e.Contains) + ")"
	case e.NotContains != "":
		return "a.not_contains(" + pyStr(e.NotContains) + ")"
	case e.Matches != "":
		return "a.matches(" + pyStr(e.Matches) + ")"
	case e.Status != 0:
		return fmt.Sprintf("a.status_is(%d)", e.Status)
	case e.Schema != "":
		return "pass  # the JSON Schema check runs in Termwright only"
	case e.MaxMs != 0 && e.Field == "" && e.JSON == "" && e.OID == "":
		return fmt.Sprintf("a.max_ms(%d)", e.MaxMs)
	case e.Field != "" || e.JSON != "" || e.OID != "":
		v := "a.json(" + pyStr(e.JSON) + ")"
		if e.OID != "" {
			v = "a.oid(" + pyStr(e.OID) + ")"
		} else if e.Field != "" {
			v = "a.field(" + pyStr(e.Field) + ")"
		}
		var c []string
		if e.Exists != nil {
			c = append(c, fmt.Sprintf(".exists(%s)", map[bool]string{true: "True", false: "False"}[*e.Exists]))
		}
		if e.Equals != nil {
			c = append(c, ".equals("+pyStr(*e.Equals)+")")
		}
		if e.NotEquals != nil {
			c = append(c, ".not_equals("+pyStr(*e.NotEquals)+")")
		}
		if e.Greater != nil {
			c = append(c, ".greater("+strconv.FormatFloat(*e.Greater, 'g', -1, 64)+")")
		}
		if e.Less != nil {
			c = append(c, ".less("+strconv.FormatFloat(*e.Less, 'g', -1, 64)+")")
		}
		if len(c) == 0 {
			c = append(c, ".is_found()")
		}
		return v + strings.Join(c, "")
	}
	return "pass  # empty check"
}

// pyStep writes one step (a loop: a Python for over its values with its steps inside).
func pyStep(b *bytes.Buffer, st Step, i int, phase, ind, suffix string) {
	if st.Loop != nil {
		var vals string
		switch {
		case len(st.Loop.Values) > 0:
			var l []string
			for _, v := range st.Loop.Values {
				l = append(l, "tw.fill("+pyStr(v)+")")
			}
			vals = "[" + strings.Join(l, ", ") + "]"
		case st.Loop.Range != "" && !strings.Contains(st.Loop.Range, "{{"):
			r, _ := rangeValues(st.Loop.Range)
			var l []string
			for _, v := range r {
				l = append(l, pyStr(v))
			}
			vals = "[" + strings.Join(l, ", ") + "]"
		default:
			src := st.Loop.From
			if src == "" {
				src = st.Loop.Range
			}
			vals = "tw.values(" + pyStr(src) + ")"
		}
		if st.If != "" {
			fmt.Fprintf(b, "%sif tw.cond(%s):\n", ind, pyStr(st.If))
			ind += "    "
		}
		x := fmt.Sprintf("x%d", strings.Count(suffix, "["))
		fmt.Fprintf(b, "%sfor %s in %s:\n%s    tw.vars[%s] = %s\n", ind, x, vals, ind, pyStr(st.Loop.Var), x)
		for j, in := range st.Loop.Steps {
			pyStep(b, in, j, phase, ind+"    ", suffix+" ["+st.Loop.Var+"={{"+st.Loop.Var+"}}]")
		}
		return
	}
	if st.Call != nil { // a procedure of lib/python/twprocs.py
		if st.If != "" {
			fmt.Fprintf(b, "%sif tw.cond(%s):\n", ind, pyStr(st.If))
			ind += "    "
		}
		var args []string
		keys := make([]string, 0, len(st.Call.With))
		for k := range st.Call.With {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			args = append(args, pyIdent(k)+"=tw.fill("+pyStr(st.Call.With[k])+")")
		}
		if phase == "cleanup" {
			args = append(args, "_cleanup=True")
		} else if st.ContinueOnFail {
			args = append(args, "_go_on=True")
		}
		fmt.Fprintf(b, "%stwprocs.%s(%s)\n", ind, pyProcName(st.Call.Proc), strings.Join(append([]string{"tw"}, args...), ", "))
		return
	}
	cont := ""
	if phase == "cleanup" {
		cont = ", cleanup=True"
	} else if st.ContinueOnFail && phase == "" {
		cont = ", continue_on_fail=True"
	}
	fmt.Fprintf(b, "%swith tw.step(%s%s) as s:\n", ind, pyStr(PhaseLabel(phase)+stepName(st, i)+suffix), cont)
	in := ind + "    "
	if st.Manual != nil {
		fmt.Fprintf(b, "%ss.skip_step(%s)\n", in, pyStr("manual step - runs in Termwright, where a person answers it: "+st.Manual.Instruction))
		return
	}
	if st.If != "" {
		fmt.Fprintf(b, "%ss.skip_unless(%s)\n", in, pyStr(st.If))
	}
	if st.Wait > 0 {
		fmt.Fprintf(b, "%ss.wait(%s)\n", in, strconv.FormatFloat(st.Wait, 'g', -1, 64))
	}
	if st.Retry != nil {
		ej, _ := json.Marshal(st.Expect)
		fmt.Fprintf(b, "%ss.retry_until(%s, %s, %s)\n", in, strconv.FormatFloat(orF(st.Retry.Timeout, 60), 'g', -1, 64), strconv.FormatFloat(orF(st.Retry.Interval, 5), 'g', -1, 64), pyStr(string(ej)))
	}
	if actions(st) == 0 {
		fmt.Fprintf(b, "%spass\n", in)
	}
	to := ""
	if st.Timeout > 0 {
		to = ", timeout=" + strconv.Itoa(st.Timeout)
	}
	if raw, ok := rawStep(st); ok { // Termwright runs it and makes its checks
		fmt.Fprintf(b, "%sa = s.raw(%s)\n", in, pyStr(raw))
		st.Expect, st.Save, st.Run, st.HTTP, st.SNMP, st.Netconf, st.Web, st.TGen = nil, nil, nil, nil, nil, nil, nil, nil
	}
	switch {
	case st.Run != nil:
		p := ""
		if st.Run.Prompt != "" {
			p = ", prompt=" + pyStr(st.Run.Prompt)
		}
		if st.Run.Parse != "" {
			p += ", parse=" + pyStr(st.Run.Parse)
		}
		fmt.Fprintf(b, "%sa = s.run(%s, %s%s%s)\n", in, pyStr(st.Run.Session), pyStr(st.Run.Command), p, to)
	case st.HTTP != nil:
		h := st.HTTP
		args := []string{pyStr(h.URL)}
		add := func(k, v string) {
			if v != "" {
				args = append(args, k+"="+pyStr(v))
			}
		}
		add("session", h.Session)
		if m := strings.ToUpper(h.Method); m != "" && m != "GET" {
			args = append(args, "method="+pyStr(m))
		}
		add("environment", h.Environment)
		add("collection", h.Collection)
		add("body", h.Body)
		if len(h.Headers) > 0 {
			args = append(args, "headers="+pyDict(h.Headers))
		}
		fmt.Fprintf(b, "%sa = s.http(%s%s)\n", in, strings.Join(args, ", "), to)
	case st.Upgrade != nil:
		fmt.Fprintf(b, "%sa = s.upgrade(%s, %s%s)\n", in, pyStr(st.Upgrade.Session), pyStr(st.Upgrade.Image), to)
	case st.Traffic != nil:
		fmt.Fprintf(b, "%sa = s.traffic(%s%s)\n", in, pyStr(st.Traffic.Test), to)
	case st.SNMP != nil:
		sn := st.SNMP
		op := strings.ToLower(sn.Op)
		if op == "" {
			op = "get"
		}
		args := []string{pyStr(sn.Session), "op=" + pyStr(op)}
		if len(sn.OIDs) > 0 {
			var o []string
			for _, x := range sn.OIDs {
				o = append(o, pyStr(x))
			}
			args = append(args, "oids=["+strings.Join(o, ", ")+"]")
		}
		if len(sn.Values) > 0 {
			var o []string
			for _, x := range sn.Values {
				o = append(o, "("+pyStr(x.OID)+", "+pyStr(x.Type)+", "+pyStr(x.Value)+")")
			}
			args = append(args, "values=["+strings.Join(o, ", ")+"]")
		}
		fmt.Fprintf(b, "%sa = s.snmp(%s%s)\n", in, strings.Join(args, ", "), to)
	}
	for _, e := range st.Expect {
		fmt.Fprintf(b, "%s%s\n", in, pyExpect(e))
	}
	for _, s := range st.Save {
		switch {
		case s.OID != "":
			fmt.Fprintf(b, "%sa.oid(%s).save(%s)\n", in, pyStr(s.OID), pyStr(s.Var))
		case s.Column != "":
			fmt.Fprintf(b, "%sa.cell(%s, %s).save(%s)\n", in, pyDict(s.Where), pyStr(s.Column), pyStr(s.Var))
		case s.Field != "":
			fmt.Fprintf(b, "%sa.field(%s).save(%s)\n", in, pyStr(s.Field), pyStr(s.Var))
		case s.JSON != "":
			fmt.Fprintf(b, "%sa.json(%s).save(%s)\n", in, pyStr(s.JSON), pyStr(s.Var))
		}
	}
}

func pyProcName(name string) string {
	n := pyIdent(strings.TrimSuffix(strings.TrimPrefix(filepath.ToSlash(name), "procs/"), ".yaml"))
	if n == "case" {
		n = "proc"
	}
	if n[0] >= '0' && n[0] <= '9' {
		n = "p_" + n
	}
	return n
}

func usesCalls(c Case) bool {
	var has func([]Step) bool
	has = func(l []Step) bool {
		for _, st := range l {
			if st.Call != nil || (st.Loop != nil && has(st.Loop.Steps)) {
				return true
			}
		}
		return false
	}
	return has(c.Setup) || has(c.Steps) || has(c.Cleanup)
}

// GeneratePyProcs writes the procedures (procs/*.yaml) as Python functions - lib/python/twprocs.py - that the
// generated tests call: twprocs.create_vlan(tw, vlan="200"). Hand-written tests can call them too.
func (f Folder) GeneratePyProcs() []byte {
	var b bytes.Buffer
	b.WriteString("# Code generated by Termwright from procs/*.yaml. DO NOT EDIT - change the procedures and save a test.\n")
	b.WriteString("\"\"\"The tests folder's procedures as functions: each runs its steps with its parameters as variables.\n\n")
	b.WriteString("    twprocs.create_vlan(tw, vlan=\"200\")      # inside a test: tw is the run (for tw in self.cases())\n\"\"\"\n\n\n")
	for _, pi := range f.Procs() {
		p, err := f.LoadProc(pi.Name)
		if err != nil {
			continue
		}
		var params, scope []string
		for _, prm := range p.Params {
			k, d, hasDef := strings.Cut(prm, "=")
			k = strings.TrimSpace(k)
			if hasDef {
				params = append(params, pyIdent(k)+"="+pyStr(strings.TrimSpace(d)))
			} else {
				params = append(params, pyIdent(k))
			}
			scope = append(scope, pyStr(k)+": "+pyIdent(k))
		}
		// parameters without a default first (Python's rule)
		sort.SliceStable(params, func(i, j int) bool { return !strings.Contains(params[i], "=") && strings.Contains(params[j], "=") })
		fmt.Fprintf(&b, "def %s(%s):\n", pyProcName(pi.Name), strings.Join(append(append([]string{"tw"}, params...), "_cleanup=False", "_go_on=False"), ", "))
		doc := p.Name
		if p.Description != "" {
			doc += ": " + oneLine(p.Description)
		}
		fmt.Fprintf(&b, "    %s\n", pyStr(doc))
		fmt.Fprintf(&b, "    with tw.scope(%s, {%s}, cleanup=_cleanup, go_on=_go_on):\n", pyStr(p.Name), strings.Join(scope, ", "))
		if len(p.Steps) == 0 {
			b.WriteString("        pass\n")
		}
		for i, st := range p.Steps {
			pyStep(&b, st, i, "", "        ", "")
		}
		b.WriteString("\n\n")
	}
	return b.Bytes()
}
