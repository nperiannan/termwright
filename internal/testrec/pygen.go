// PyFile is the generated Python test of a case file: cases/vlan/add.yaml → cases/vlan/test_vlan_add.py
// (the folder in the name keeps file names unique for pytest without __init__ files).
func PyFile(caseFile string) string {
	caseFile = filepath.ToSlash(caseFile)
	dir, base := filepath.ToSlash(filepath.Dir(caseFile)), strings.TrimSuffix(filepath.Base(caseFile), filepath.Ext(caseFile))
	sub := strings.TrimPrefix(strings.TrimPrefix(dir, "cases"), "/")
	name := pyIdent(base)
	if sub != "" {
		name = pyIdent(strings.ReplaceAll(sub, "/", "_")) + "_" + name
	}
	return dir + "/test_" + name + ".py"
}

func pyIdent(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			b.WriteRune(r)
		case b.Len() > 0 && !strings.HasSuffix(b.String(), "_"):
			b.WriteByte('_')
		}
	}
	if n := strings.Trim(b.String(), "_"); n != "" {
		return n
	}
	return "case"
}

// pyStr quotes s for Python: a raw string for regular expressions with backslashes, else a JSON
// string (valid Python).
func pyStr(s string) string {
	if strings.Contains(s, `\`) && !strings.ContainsAny(s, "'\n\r") && !strings.HasSuffix(s, `\`) {
		return "r'" + s + "'"
	}
	b, _ := json.Marshal(s)
	return string(b)
}

func pyDict(m map[string]string) string {
	if len(m) == 0 {
		return "{}"
	}
	b, _ := json.Marshal(m) // sorted keys; valid Python
	return string(b)
}

// GeneratePython writes a case as a Python test (unittest.TestCase from lib/python/twtest.py; pytest
// runs it too); each step is a subTest.
func GeneratePython(c Case, caseFile string) ([]byte, error) {
	caseFile = filepath.ToSlash(caseFile)
	depth := strings.Count(filepath.ToSlash(filepath.Dir(caseFile)), "/") + 1
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Code generated by Termwright from %s. DO NOT EDIT - change the YAML (or record it again) and save it.\n", caseFile)
	b.WriteString("import os\nimport sys\n\n")
	fmt.Fprintf(&b, "sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), %s\"lib\", \"python\"))\n", strings.Repeat(`"..", `, depth))
	b.WriteString("import twtest  # noqa: E402\n\n\n")
	base := strings.TrimSuffix(filepath.Base(caseFile), filepath.Ext(caseFile))
	name := c.Name
	if name == "" {
		name = base
	}
	fmt.Fprintf(&b, "class Test%s(twtest.TestCase):\n", goIdent(base))
	doc := oneLine(name)
	if c.Description != "" {
		doc += ": " + oneLine(c.Description)
	}
	fmt.Fprintf(&b, "    %s\n\n    VARS = %s\n", pyStr(doc), pyDict(c.Vars))
	if len(c.Params) > 0 {
		var ps []string
		for _, p := range c.Params {
			ps = append(ps, pyDict(p))
		}
		fmt.Fprintf(&b, "    PARAMS = [%s]\n", strings.Join(ps, ", "))
	}
	b.WriteString("\n    def test_steps(self):\n        for tw in self.cases():\n")
	ind := "            "
	for i, st := range c.Steps {
		cont := ""
		if st.ContinueOnFail {
			cont = ", continue_on_fail=True"
		}
		fmt.Fprintf(&b, "%swith tw.step(%s%s) as s:\n", ind, pyStr(stepName(st, i)), cont)
		in := ind + "    "
		to := ""
		if st.Timeout > 0 {
			to = ", timeout=" + strconv.Itoa(st.Timeout)
		}
		switch {
		case st.Run != nil:
			p := ""
			if st.Run.Prompt != "" {
				p = ", prompt=" + pyStr(st.Run.Prompt)
			}
			fmt.Fprintf(&b, "%sa = s.run(%s, %s%s%s)\n", in, pyStr(st.Run.Session), pyStr(st.Run.Command), p, to)
		case st.HTTP != nil:
			h := st.HTTP
			args := []string{pyStr(h.URL)}
			add := func(k, v string) {
				if v != "" {
					args = append(args, k+"="+pyStr(v))
				}
			}
			add("session", h.Session)
			if m := strings.ToUpper(h.Method); m != "" && m != "GET" {
				args = append(args, "method="+pyStr(m))
			}
			add("environment", h.Environment)
			add("collection", h.Collection)
			add("body", h.Body)
			if len(h.Headers) > 0 {
				args = append(args, "headers="+pyDict(h.Headers))
			}
			fmt.Fprintf(&b, "%sa = s.http(%s%s)\n", in, strings.Join(args, ", "), to)
		case st.SNMP != nil:
			sn := st.SNMP
			op := strings.ToLower(sn.Op)
			if op == "" {
				op = "get"
			}
			args := []string{pyStr(sn.Session), "op=" + pyStr(op)}
			if len(sn.OIDs) > 0 {
				var o []string
				for _, x := range sn.OIDs {
					o = append(o, pyStr(x))
				}
				args = append(args, "oids=["+strings.Join(o, ", ")+"]")
			}
			if len(sn.Values) > 0 {
				var o []string
				for _, x := range sn.Values {
					o = append(o, "("+pyStr(x.OID)+", "+pyStr(x.Type)+", "+pyStr(x.Value)+")")
				}
				args = append(args, "values=["+strings.Join(o, ", ")+"]")
			}
			fmt.Fprintf(&b, "%sa = s.snmp(%s%s)\n", in, strings.Join(args, ", "), to)
		}
		for _, e := range st.Expect {
			fmt.Fprintf(&b, "%s%s\n", in, pyExpect(e))
		}
		for _, s := range st.Save {
			switch {
			case s.OID != "":
				fmt.Fprintf(&b, "%sa.oid(%s).save(%s)\n", in, pyStr(s.OID), pyStr(s.Var))
			case s.Field != "":
				fmt.Fprintf(&b, "%sa.field(%s).save(%s)\n", in, pyStr(s.Field), pyStr(s.Var))
			case s.JSON != "":
				fmt.Fprintf(&b, "%sa.json(%s).save(%s)\n", in, pyStr(s.JSON), pyStr(s.Var))
			}
		}
	}
	if len(c.Steps) == 0 {
		b.WriteString(ind + "self.fail(\"the test has no steps\")\n")
	}
	return b.Bytes(), nil
}

func pyExpect(e Expect) string {
	switch {
	case e.Contains != "":
		return "a.contains(" + pyStr(e.Contains) + ")"
	case e.NotContains != "":
		return "a.not_contains(" + pyStr(e.NotContains) + ")"
	case e.Matches != "":
		return "a.matches(" + pyStr(e.Matches) + ")"
	case e.Status != 0:
		return fmt.Sprintf("a.status_is(%d)", e.Status)
	case e.MaxMs != 0 && e.Field == "" && e.JSON == "" && e.OID == "":
		return fmt.Sprintf("a.max_ms(%d)", e.MaxMs)
	case e.Field != "" || e.JSON != "" || e.OID != "":
		v := "a.json(" + pyStr(e.JSON) + ")"
		if e.OID != "" {
			v = "a.oid(" + pyStr(e.OID) + ")"
		} else if e.Field != "" {
			v = "a.field(" + pyStr(e.Field) + ")"
		}
		var c []string
		if e.Exists != nil {
			c = append(c, fmt.Sprintf(".exists(%s)", map[bool]string{true: "True", false: "False"}[*e.Exists]))
		}
		if e.Equals != nil {
			c = append(c, ".equals("+pyStr(*e.Equals)+")")
		}
		if e.NotEquals != nil {
			c = append(c, ".not_equals("+pyStr(*e.NotEquals)+")")
		}
		if e.Greater != nil {
			c = append(c, ".greater("+strconv.FormatFloat(*e.Greater, 'g', -1, 64)+")")
		}
		if e.Less != nil {
			c = append(c, ".less("+strconv.FormatFloat(*e.Less, 'g', -1, 64)+")")
		}
		if len(c) == 0 {
			c = append(c, ".is_found()")
		}
		return v + strings.Join(c, "")
	}
	return "pass  # empty check"
}
