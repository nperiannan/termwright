// TclFile is the generated TCL test of a case file: cases/vlan/add.yaml → cases/vlan/add.test.tcl.
func TclFile(caseFile string) string {
	return strings.TrimSuffix(filepath.ToSlash(caseFile), filepath.Ext(caseFile)) + ".test.tcl"
}

// tclStr quotes s as one Tcl word: in braces when that keeps it as it is, else in double quotes
// with the special characters escaped.
func tclStr(s string) string {
	depth, ok := 0, !strings.HasSuffix(s, `\`) && !strings.Contains(s, "\\\n")
	for i := 0; i < len(s) && ok; i++ {
		switch s[i] {
		case '\\':
			i++
		case '{':
			depth++
		case '}':
			depth--
			ok = depth >= 0
		}
	}
	if ok && depth == 0 {
		return "{" + s + "}"
	}
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`, `[`, `\[`, `]`, `\]`, `{`, `\{`, `}`, `\}`, "\n", `\n`, "\r", `\r`, "\t", `\t`)
	return `"` + r.Replace(s) + `"`
}

func tclDict(m map[string]string) string {
	if len(m) == 0 {
		return "{}"
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var p []string
	for _, k := range keys {
		p = append(p, tclStr(k), tclStr(m[k]))
	}
	return "[list " + strings.Join(p, " ") + "]"
}

// GenerateTcl writes a case as a TCL script using lib/tcl/twtest.tcl (TAP output, exit code 1 when a
// step failed).
func GenerateTcl(c Case, caseFile string) ([]byte, error) {
	caseFile = filepath.ToSlash(caseFile)
	depth := strings.Count(filepath.ToSlash(filepath.Dir(caseFile)), "/") + 1
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Code generated by Termwright from %s. DO NOT EDIT - change the YAML (or record it again) and save it.\n", caseFile)
	fmt.Fprintf(&b, "source [file join [file dirname [file normalize [info script]]] %slib tcl twtest.tcl]\n\n", strings.Repeat(".. ", depth))
	name := c.Name
	if name == "" {
		name = strings.TrimSuffix(filepath.Base(caseFile), filepath.Ext(caseFile))
	}
	params := "{}"
	if len(c.Params) > 0 {
		var ps []string
		for _, p := range c.Params {
			ps = append(ps, tclDict(p))
		}
		params = "[list " + strings.Join(ps, " ") + "]"
	}
	if c.Description != "" {
		fmt.Fprintf(&b, "# %s\n", oneLine(c.Description))
	}
	fmt.Fprintf(&b, "tw::test %s %s %s {\n", tclStr(oneLine(name)), tclDict(c.Vars), params)
	if len(c.Restore) > 0 {
		var ss []string
		for _, x := range Sessions(c, nil) {
			ss = append(ss, tclStr(x))
		}
		fmt.Fprintf(&b, "    tw::restore [list %s] [list %s]\n", strings.Join(c.Restore, " "), strings.Join(ss, " "))
	}
	for _, ps := range phased(c) {
		tclStep(&b, ps.st, ps.i, ps.phase, "    ", "")
	}
	if len(c.Restore) > 0 {
		b.WriteString("    tw::finish\n")
	}
	b.WriteString("}\ntw::done\n")
	return b.Bytes(), nil
}

func tclExpect(e Expect) []string {
	switch {
	case e.Table != nil:
		t := e.Table
		pre := "tw::table " + tclDict(t.Where) + " " + tclStr(t.Column) + " "
		switch {
		case t.Rows != nil:
			return []string{"tw::table " + tclDict(t.Where) + " {} equals " + strconv.Itoa(*t.Rows)}
		case t.Column == "" && t.Exists != nil && !*t.Exists:
			return []string{pre + "missing"}
		case t.Column == "":
			return []string{pre + "exists"}
		case t.Matches != "":
			return []string{pre + "matches " + tclStr(t.Matches)}
		}
		var out []string
		if t.Exists != nil {
			out = append(out, pre+map[bool]string{true: "exists", false: "missing"}[*t.Exists])
		}
		if t.Equals != nil {
			out = append(out, pre+"equals "+tclStr(*t.Equals))
		}
		if t.NotEquals != nil {
			out = append(out, pre+"not_equals "+tclStr(*t.NotEquals))
		}
		if t.Greater != nil {
			out = append(out, pre+"greater "+strconv.FormatFloat(*t.Greater, 'g', -1, 64))
		}
		if t.Less != nil {
			out = append(out, pre+"less "+strconv.FormatFloat(*t.Less, 'g', -1, 64))
		}
		if len(out) == 0 {
			out = append(out, pre+"exists")
		}
		return out
	case e.Contains != "":
		return []string{"tw::contains " + tclStr(e.Contains)}
	case e.NotContains != "":
		return []string{"tw::not_contains " + tclStr(e.NotContains)}
	case e.Matches != "":
		return []string{"tw::matches " + tclStr(e.Matches)}
	case e.Status != 0:
		return []string{fmt.Sprintf("tw::status %d", e.Status)}
	case e.Schema != "":
		return []string{"# the JSON Schema check runs in Termwright only"}
	case e.MaxMs != 0 && e.Field == "" && e.JSON == "" && e.OID == "":
		return []string{fmt.Sprintf("tw::max_ms %d", e.MaxMs)}
	case e.Field != "" || e.JSON != "" || e.OID != "":
		kind, subj := "json", e.JSON
		if e.OID != "" {
			kind, subj = "oid", e.OID
		} else if e.Field != "" {
			kind, subj = "field", e.Field
		}
		pre := "tw::check " + kind + " " + tclStr(subj) + " "
		var out []string
		if e.Exists != nil {
			out = append(out, pre+map[bool]string{true: "exists", false: "missing"}[*e.Exists])
		}
		if e.Equals != nil {
			out = append(out, pre+"equals "+tclStr(*e.Equals))
		}
		if e.NotEquals != nil {
			out = append(out, pre+"not_equals "+tclStr(*e.NotEquals))
		}
		if e.Greater != nil {
			out = append(out, pre+"greater "+strconv.FormatFloat(*e.Greater, 'g', -1, 64))
		}
		if e.Less != nil {
			out = append(out, pre+"less "+strconv.FormatFloat(*e.Less, 'g', -1, 64))
		}
		if len(out) == 0 {
			out = append(out, pre+"found")
		}
		return out
	}
	return []string{"# empty check"}
}

// tclStep writes one step (a loop: a foreach over its values with its steps inside).
func tclStep(b *bytes.Buffer, st Step, i int, phase, ind, suffix string) {
	if st.Loop != nil {
		var vals string
		switch {
		case len(st.Loop.Values) > 0:
			var l []string
			for _, v := range st.Loop.Values {
				l = append(l, tclStr(v))
			}
			vals = "[tw::listof " + strings.Join(l, " ") + "]"
		case st.Loop.Range != "" && !strings.Contains(st.Loop.Range, "{{"):
			r, _ := rangeValues(st.Loop.Range)
			var l []string
			for _, v := range r {
				l = append(l, tclStr(v))
			}
			vals = "[list " + strings.Join(l, " ") + "]"
		default:
			src := st.Loop.From
			if src == "" {
				src = st.Loop.Range
			}
			vals = "[tw::values " + tclStr(src) + "]"
		}
		if st.If != "" {
			fmt.Fprintf(b, "%sif {[tw::cond %s]} {\n", ind, tclStr(st.If))
		}
		x := fmt.Sprintf("x%d", strings.Count(suffix, "["))
		fmt.Fprintf(b, "%sforeach %s %s {\n%s    tw::setvar %s $%s\n", ind, x, vals, ind, tclStr(st.Loop.Var), x)
		for j, in := range st.Loop.Steps {
			tclStep(b, in, j, phase, ind+"    ", suffix+" ["+st.Loop.Var+"={{"+st.Loop.Var+"}}]")
		}
		fmt.Fprintf(b, "%s}\n", ind)
		if st.If != "" {
			fmt.Fprintf(b, "%s}\n", ind)
		}
		return
	}
	if phase == "cleanup" {
		fmt.Fprintf(b, ind+"tw::cleanup %s {\n", tclStr(PhaseLabel(phase)+stepName(st, i)+suffix))
	} else {
		fmt.Fprintf(b, ind+"tw::step %s %d {\n", tclStr(PhaseLabel(phase)+stepName(st, i)+suffix), map[bool]int{true: 1, false: 0}[st.ContinueOnFail && phase == ""])
	}
	in := ind + "    "
	if st.Manual != nil {
		fmt.Fprintf(b, "%s# manual step - runs in Termwright, where a person answers it\n%s}\n", in, ind)
		return
	}
	if st.Wait > 0 {
		fmt.Fprintf(b, "%safter %d\n", in, int(st.Wait*1000))
	}
	if st.Retry != nil {
		ej, _ := json.Marshal(st.Expect)
		fmt.Fprintf(b, "%stw::retry_until %s %s %s\n", in, strconv.FormatFloat(orF(st.Retry.Timeout, 60), 'g', -1, 64), strconv.FormatFloat(orF(st.Retry.Interval, 5), 'g', -1, 64), tclStr(string(ej)))
	}
	if st.If != "" {
		fmt.Fprintf(b, "%sif {[tw::cond %s]} {\n", in, tclStr(st.If))
		in += "    "
	}
	if raw, ok := rawStep(st); ok { // Termwright runs it and makes its checks
		fmt.Fprintf(b, "%stw::raw %s\n", in, tclStr(raw))
		st.Expect, st.Save, st.Run, st.HTTP, st.SNMP, st.Netconf, st.Web, st.TGen = nil, nil, nil, nil, nil, nil, nil, nil
	}
	switch {
	case st.Run != nil:
		args := []string{tclStr(st.Run.Session), tclStr(st.Run.Command)}
		if st.Run.Prompt != "" || st.Timeout > 0 || st.Run.Parse != "" {
			args = append(args, tclStr(st.Run.Prompt), strconv.Itoa(st.Timeout))
		}
		if st.Run.Parse != "" {
			args = append(args, tclStr(st.Run.Parse))
		}
		fmt.Fprintf(b, "%stw::run %s\n", in, strings.Join(args, " "))
	case st.HTTP != nil:
		h := st.HTTP
		args := []string{tclStr(h.URL)}
		add := func(k, v string) {
			if v != "" {
				args = append(args, k, tclStr(v))
			}
		}
		add("-session", h.Session)
		if m := strings.ToUpper(h.Method); m != "" && m != "GET" {
			args = append(args, "-method", m)
		}
		add("-environment", h.Environment)
		add("-collection", h.Collection)
		add("-body", h.Body)
		if len(h.Headers) > 0 {
			args = append(args, "-headers", tclDict(h.Headers))
		}
		if st.Timeout > 0 {
			args = append(args, "-timeout", strconv.Itoa(st.Timeout))
		}
		fmt.Fprintf(b, "%stw::http %s\n", in, strings.Join(args, " "))
	case st.Upgrade != nil:
		fmt.Fprintf(b, "%stw::upgrade %s %s %d\n", in, tclStr(st.Upgrade.Session), tclStr(st.Upgrade.Image), st.Timeout)
	case st.Traffic != nil:
		fmt.Fprintf(b, "%stw::traffic %s %d\n", in, tclStr(st.Traffic.Test), st.Timeout)
	case st.SNMP != nil:
		sn := st.SNMP
		op := strings.ToLower(sn.Op)
		if op == "" {
			op = "get"
		}
		var o []string
		for _, x := range sn.OIDs {
			o = append(o, tclStr(x))
		}
		var v []string
		for _, x := range sn.Values {
			v = append(v, "[list "+tclStr(x.OID)+" "+tclStr(x.Type)+" "+tclStr(x.Value)+"]")
		}
		fmt.Fprintf(b, "%stw::snmp %s %s [list %s] [list %s] %d\n", in, tclStr(sn.Session), op, strings.Join(o, " "), strings.Join(v, " "), st.Timeout)
	}
	for _, e := range st.Expect {
		for _, l := range tclExpect(e) {
			fmt.Fprintf(b, "%s%s\n", in, l)
		}
	}
	for _, s := range st.Save {
		switch {
		case s.OID != "":
			fmt.Fprintf(b, "%stw::save %s oid %s\n", in, tclStr(s.Var), tclStr(s.OID))
		case s.Column != "":
			fmt.Fprintf(b, "%stw::save_cell %s %s %s\n", in, tclStr(s.Var), tclDict(s.Where), tclStr(s.Column))
		case s.Field != "":
			fmt.Fprintf(b, "%stw::save %s field %s\n", in, tclStr(s.Var), tclStr(s.Field))
		case s.JSON != "":
			fmt.Fprintf(b, "%stw::save %s json %s\n", in, tclStr(s.Var), tclStr(s.JSON))
		}
	}
	if st.If != "" {
		fmt.Fprintf(b, "%s}\n", in[:len(in)-4])
	}
	b.WriteString(ind + "}\n")
}
